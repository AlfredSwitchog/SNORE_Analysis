function p = tTestP(t, df)
    % Two-sided p-value of a t statistic, without the Statistics Toolbox.
    % Uses the identity  P(|T|>t) = I_{df/(df+t^2)}(df/2, 1/2),
    % where I is the regularised incomplete beta function (betainc).
    p = betainc(df ./ (df + t.^2), df/2, 0.5);
    p(~isfinite(t)) = NaN;
end

function [sig, pAdj] = fdrBH(p, q)
    % Benjamini-Hochberg FDR. Returns the reject mask at level q and the
    % BH-adjusted p-values (monotone, capped at 1).
    p = p(:).';  m = numel(p);
    [ps, ord] = sort(p);

    % reject the k smallest p-values, where k is the largest index with
    % p(k) <= q*k/m
    below = find(ps <= q * (1:m) / m, 1, 'last');
    sig = false(1, m);
    if ~isempty(below); sig(ord(1:below)) = true; end

    % adjusted p-values: step-up, enforced monotone from the largest down
    adjS = ps .* m ./ (1:m);
    for k = m-1:-1:1
        adjS(k) = min(adjS(k), adjS(k+1));
    end
    pAdj = zeros(1, m);
    pAdj(ord) = min(adjS, 1);
end
