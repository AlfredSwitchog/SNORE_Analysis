%% ============================================================
%  gBOLD - CSF lagged cross-correlation:  TWO-STAGE GROUP ANALYSIS
%  ------------------------------------------------------------
%  Fixes the pseudoreplication problem of pooling epochs across
%  participants: here the unit of inference is the PARTICIPANT.
%
%  STAGE 1  (per participant -- ESTIMATION ONLY, no testing)
%     for each epoch, for each lag L:  r = corr(gBOLD, CSF shifted by L)
%     -> Fisher-z transform      z = atanh(r)
%     -> average z across that participant's epochs
%     => ONE z-curve per participant
%
%  STAGE 2  (across participants -- INFERENCE)
%     at each lag: one-sample t-test of the participants' z against 0
%     -> Benjamini-Hochberg FDR across the lags
%     -> mean z transformed back to r (tanh) for plotting
%
%  ONE OR SEVERAL CONDITIONS
%     stageLabels may list one stage set or several. With several, each
%     condition is run through both stages separately and all curves are
%     drawn into ONE figure (e.g. sleep vs. wake control).
%
%  CONVENTION:   r(L) = corr( gBOLD(t), CSF(t + L) )
%     positive lag L  ->  CSF sampled LATER   ->  "CSF follows gBOLD"
%     negative lag L  ->  CSF sampled EARLIER ->  "CSF leads gBOLD"
%  This is the SAME convention as csf_gm_cross_correlation_within_epoch.m,
%  so the two analyses can be compared directly.
%
%  ATTENTION: The axis are flipped in the end to represent the Plots
%  generated by previous studies (HAN et al.). This is not reversing the results this is
%  just a different defintion of what a psoitive Lag means verablly vs.
%  what it does in the code
%
%  Lags never cross an epoch border: every correlation is computed inside
%  one continuous epoch, on the overlapping window only.
%
%  Base MATLAB only - no Statistics Toolbox required.
%  1 TR = 1 volume = 2.5 s.
% ============================================================

%% ---------------- CONFIG ----------------
% Sleep-stage definition(s). Drives ALL folder names.
% Allowed entries: "N2" | "N2_N3" | "N1_N2_N3" | "W"
%   ONE entry   -> single-condition figure, saved under <stage>/within_epoch/group_level
%   TWO or more -> all curves in one figure, saved under multi_stage
% The FIRST entry is treated as the primary condition (it gets the peak
% annotation and is drawn on top).
stageLabels = ["N1_N2_N3", "W"];

% Participants to analyse. [] = every participant found in the CSF folder.
% Otherwise a list of numbers, e.g. [5 8 22 23]
subjects   = [];

% With several conditions: restrict to participants that contribute a
% curve in EVERY condition, so the comparison is within the same people.
% Strongly recommended for the sleep-vs-wake contrast.
matchSubjects = true;

TR         = 2.5;    % seconds per TR / volume
maxLagTR   = 5;      % lags -5..+5 TR  (= -12.5 .. +12.5 s)
alphaFDR   = 0.05;   % FDR level for the Benjamini-Hochberg correction

% How to combine a participant's epochs in Stage 1:
%   "invvar" - weight each epoch by (n_overlap - 3), the inverse variance
%              of a Fisher-z value. Long epochs give more reliable r and
%              therefore count more. RECOMMENDED: epoch lengths here range
%              from 36 to >900 TR, so equal weighting adds a lot of noise.
%   "equal"  - plain unweighted mean across epochs.
epochWeighting = "invvar";

minOverlapTR = 10;   % skip an epoch/lag if fewer samples than this overlap

% What is correlated against the CSF signal.
%   "none"            - the gBOLD signal itself. gBOLD is a STATE (a proxy
%                       for blood volume), the CSF signal is a FLOW, so the
%                       two are not the same kind of quantity.
%   "negderiv"        - the NEGATIVE time derivative of gBOLD, i.e. how fast
%                       blood volume is FALLING. This turns gBOLD into a
%                       flow, so both signals are the same kind of quantity.
%                       Follows Han et al. (2021).
%   "negderiv_thresh" - as "negderiv", but negative values are set to zero,
%                       keeping only the phase in which blood is leaving.
%                       Follows Fultz et al. (2019), whose CSF measurement
%                       can see inflow but not outflow.
gboldTransform = "negderiv";

% Lag axis orientation FOR THE PLOT ONLY. The computation, the console
% table and the saved .mat are ALWAYS in this script's own convention and
% are never touched by this switch.
flipLagAxisForDisplay = false;

saveResults  = true; % write a .mat with all per-participant curves + stats
dpi          = 200;

% ---- roots (note the different capitalisation of the two data roots) ----
csfRoot  = '/Users/Richard/Masterabeit_local/SNORE_CSF_Data/Sleep_Stage_Segmented';
gmRoot   = '/Users/Richard/Masterabeit_local/SNORE_GM_Data/sleep_stage_segmented';
plotRoot = '/Users/Richard/Masterabeit_local/SNORE_Plots/Cross_Correlaltion';

%% ---------------- DERIVED PATHS AND LAGS ----------------
stageLabels = string(stageLabels(:)).';
nCond       = numel(stageLabels);

lagsTR  = -maxLagTR:maxLagTR;      % 1 x nLags
lagsSec = lagsTR * TR;             % native convention, used everywhere
nLags   = numel(lagsTR);

% display-only mirroring of the x-axis (see flipLagAxisForDisplay above)
if flipLagAxisForDisplay
    lagSign = -1;
    lagAxisNote = 'positive = CSF LEADS gBOLD';
    axisTag = '_FlippedAxis';
else
    lagSign = 1;
    lagAxisNote = 'positive = CSF follows gBOLD';
    axisTag = '';
end
lagsPlot = lagsSec * lagSign;

% file-name prefix and human-readable name for the chosen gBOLD transform
switch string(gboldTransform)
    case "none"
        transformTag = '';           transformNote = 'gBOLD';
    case "negderiv"
        transformTag = 'deriv_';     transformNote = '-d(gBOLD)/dt';
    case "negderiv_thresh"
        transformTag = 'derivthr_';  transformNote = '-d(gBOLD)/dt, zero-thresholded';
    otherwise
        error('Unknown gboldTransform "%s".', gboldTransform);
end

% where the figure and the .mat go
if nCond == 1
    outDir  = fullfile(plotRoot, char(stageLabels(1)), 'within_epoch', 'group_level');
    fileTag = char(stageLabels(1));
else
    outDir  = fullfile(plotRoot, 'multi_stage');
    fileTag = char(strjoin(stageLabels, '_vs_'));
end
if ~exist(outDir, 'dir'); mkdir(outDir); end

fprintf('\n================ TWO-STAGE GROUP CROSS-CORRELATION ================\n');
fprintf('Conditions: %s\n', strjoin(stageLabels, ', '));
fprintf('Lags      : %d..%d TR  (%.1f..%.1f s)\n', ...
        lagsTR(1), lagsTR(end), lagsSec(1), lagsSec(end));
fprintf('Weighting : %s\n', epochWeighting);
fprintf('Signal    : %s  vs  CSF\n', transformNote);
fprintf('Plot axis : %s\n', lagAxisNote);
fprintf('Output    : %s\n', outDir);
fprintf('===================================================================\n');

%% =====================================================================
%  STAGE 1 - run for every condition
%  =====================================================================
S1 = cell(1, nCond);
for k = 1:nCond
    S1{k} = stage1ForCondition(stageLabels(k), csfRoot, gmRoot, subjects, ...
                               lagsTR, minOverlapTR, epochWeighting, ...
                               TR, gboldTransform);
end

%% ---- optionally restrict to participants present in ALL conditions ----
if nCond > 1 && matchSubjects
    common = S1{1}.subjIDs;
    for k = 2:nCond
        common = intersect(common, S1{k}.subjIDs);
    end
    fprintf('\nMatching participants across conditions: %d in common (%s)\n', ...
            numel(common), strjoin("P" + string(common), ', '));
    for k = 1:nCond
        dropped = setdiff(S1{k}.subjIDs, common);
        if ~isempty(dropped)
            fprintf('   %-10s drops %s\n', stageLabels(k), ...
                    strjoin("P" + string(dropped), ', '));
        end
        keep            = ismember(S1{k}.subjIDs, common);
        S1{k}.subjIDs   = S1{k}.subjIDs(keep);
        S1{k}.Z         = S1{k}.Z(keep,:);
        S1{k}.nEpUsed   = S1{k}.nEpUsed(keep);
    end
end

%% =====================================================================
%  STAGE 2 - inference, per condition
%  =====================================================================
for k = 1:nCond
    nSubj = numel(S1{k}.subjIDs);
    assert(nSubj >= 2, ...
        'Condition %s: need at least 2 participants for a group test (have %d).', ...
        stageLabels(k), nSubj);

    S2 = stage2(S1{k}.Z, alphaFDR);

    fprintf('\n===== %s : STAGE 2 across participants (n = %d, df = %d) =====\n', ...
            stageLabels(k), nSubj, nSubj-1);
    fprintf('%6s %8s %9s %9s %9s %9s  %s\n', ...
            'lag_TR','lag_s','mean_r','t','p','p_FDR','sig');
    fprintf('%s\n', repmat('-',1,64));
    for j = 1:nLags
        if S2.sigFDR(j); mark = '*'; else; mark = ''; end
        fprintf('%6d %8.2f %9.4f %9.3f %9.4f %9.4f  %s\n', ...
                lagsTR(j), lagsSec(j), S2.meanR(j), S2.tStat(j), ...
                S2.pRaw(j), S2.pAdj(j), mark);
    end
    fprintf('%s\n', repmat('-',1,64));
    [~, iNeg] = min(S2.meanR);
    [~, iPos] = max(S2.meanR);
    fprintf('negative peak: r=%+.3f at %+.1f s (%+d TR), p_FDR=%.4f\n', ...
            S2.meanR(iNeg), lagsSec(iNeg), lagsTR(iNeg), S2.pAdj(iNeg));
    fprintf('positive peak: r=%+.3f at %+.1f s (%+d TR), p_FDR=%.4f\n', ...
            S2.meanR(iPos), lagsSec(iPos), lagsTR(iPos), S2.pAdj(iPos));

    S1{k}.stats = S2;
    S1{k}.nSubj = nSubj;
    S1{k}.iNeg  = iNeg;
    S1{k}.iPos  = iPos;
end

%% =====================================================================
%  GROUP-LEVEL PLOT  (all conditions in one figure)
%  =====================================================================
palette = [0.15 0.35 0.70;      % blue    - primary condition
           0.85 0.33 0.10;      % orange  - control
           0.20 0.60 0.25;      % green
           0.50 0.20 0.60];     % purple

fig = figure('Visible','off', 'Color','w', 'Position',[100 100 900 540]);
hold on;

hCurve = gobjects(1, nCond);        % handles, so the legend order can be set
hFDR   = gobjects(1, nCond);
hBand  = gobjects(1);

% --- SE bands first, so the lines are drawn on top of them ---
for k = nCond:-1:1
    col = palette(mod(k-1, size(palette,1))+1, :);
    st  = S1{k}.stats;
    hb  = fill([lagsPlot, fliplr(lagsPlot)], [st.ciHiR, fliplr(st.ciLoR)], col, ...
               'FaceAlpha', 0.15, 'EdgeColor','none');
    if k == 1
        set(hb, 'DisplayName', '\pm1 SE across participants');
        hBand = hb;
    else
        set(hb, 'HandleVisibility','off');
    end
end

% reference lines - kept out of the legend, otherwise they show as data1/data2
yline(0, 'k-', 'HandleVisibility','off');
xline(0, 'k:', 'HandleVisibility','off');

% --- the curves, primary condition drawn last so it sits on top ---
for k = nCond:-1:1
    col  = palette(mod(k-1, size(palette,1))+1, :);
    st   = S1{k}.stats;
    name = prettyStageName(stageLabels(k));

    hCurve(k) = plot(lagsPlot, st.meanR, '-o', 'Color',col, 'LineWidth',1.8, ...
         'MarkerFaceColor',col, 'MarkerSize',5, ...
         'DisplayName', sprintf('%s  (n = %d)', name, S1{k}.nSubj));

    % every condition gets its own FDR entry, in its own colour
    if any(st.sigFDR)
        hFDR(k) = plot(lagsPlot(st.sigFDR), st.meanR(st.sigFDR), 'o', ...
                  'MarkerEdgeColor',col, 'MarkerFaceColor','none', ...
                  'MarkerSize',11, 'LineWidth',1.5, ...
                  'DisplayName', sprintf('%s  FDR q<%.2f', name, alphaFDR));
    end
end

% --- peak annotation for the PRIMARY condition only ---
%   raw gBOLD  : the NEGATIVE peak is the coupling index used by Han et al.
%   derivative : the POSITIVE peak near lag 0 is the result of interest, so
%                the negative peak is not annotated
st1  = S1{1}.stats;
col1 = palette(1,:);
if string(gboldTransform) == "none"
    iAnn = S1{1}.iNeg;  annName = 'neg. peak';  annMark = 'v';  annAlign = 'top';
else
    iAnn = S1{1}.iPos;  annName = 'peak';       annMark = '^';  annAlign = 'bottom';
end
plot(lagsPlot(iAnn), st1.meanR(iAnn), annMark, 'Color',col1, ...
     'MarkerFaceColor',col1, 'MarkerSize',9, 'HandleVisibility','off');
text(lagsPlot(iAnn), st1.meanR(iAnn), ...
     sprintf('  %s %.1f s, r=%.3f', annName, lagsPlot(iAnn), st1.meanR(iAnn)), ...
     'Color',col1, 'VerticalAlignment',annAlign, 'FontSize',9);

hold off;
xlabel(sprintf('Lag (s)     [ %s ]', lagAxisNote));
ylabel(sprintf('Pearson correlation   (%s vs CSF)', transformNote));
prettyNames = arrayfun(@prettyStageName, stageLabels);
if nCond == 1
    title(sprintf('%s vs CSF cross-correlation  -  %s, two-stage, n = %d', ...
                  transformNote, prettyNames(1), S1{1}.nSubj), 'Interpreter','none');
else
    title(sprintf('%s vs CSF cross-correlation  -  %s (two-stage)', ...
                  transformNote, strjoin(prettyNames, ' vs ')), 'Interpreter','none');
end
xticks(sort(lagsPlot)); xlim([min(lagsPlot) max(lagsPlot)]); grid off;

% legend in a fixed order: primary condition first, SE band last
legHandles = gobjects(0);
for k = 1:nCond
    legHandles(end+1) = hCurve(k);                                  %#ok<SAGROW>
    if isgraphics(hFDR(k)); legHandles(end+1) = hFDR(k); end        %#ok<SAGROW>
