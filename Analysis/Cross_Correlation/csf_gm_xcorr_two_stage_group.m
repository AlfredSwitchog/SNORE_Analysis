if isgraphics(hBand); legHandles(end+1) = hBand; end
legend(legHandles, 'Location','northwest', 'Box','off');

if nCond == 1
    outPng = fullfile(outDir, sprintf('group_xcorr_%s%s_twostage_n%d%s.png', ...
                                      transformTag, fileTag, S1{1}.nSubj, axisTag));
else
    outPng = fullfile(outDir, sprintf('group_xcorr_%s%s_twostage%s.png', ...
                                      transformTag, fileTag, axisTag));
end
try
    exportgraphics(fig, outPng, 'Resolution', dpi);
