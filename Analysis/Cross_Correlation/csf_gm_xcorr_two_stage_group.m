%% ======================= CONDITION RUNNERS =======================
function out = stage1ForCondition(stageLabel, csfRoot, gmRoot, subjects, ...
                                  lagsTR, minOverlapTR, epochWeighting, ...
                                  TR, gboldTransform)
    % Stage 1 for ONE stage definition -> one Fisher-z curve per participant.
    csfDir = fullfile(csfRoot, char(stageLabel));
    gmDir  = fullfile(gmRoot,  char(stageLabel));

    D = dir(fullfile(csfDir, sprintf('csf_p*_%s.mat', stageLabel)));
    assert(~isempty(D), 'No csf_p*_%s.mat in %s', stageLabel, csfDir);

    fprintf('\n===== %s : STAGE 1 within participant =====\n', stageLabel);
    fprintf('CSF dir   : %s\n', csfDir);
    fprintf('GM  dir   : %s\n', gmDir);
    fprintf('%-7s %8s %9s %10s   %s\n', 'Subj','#epochs','usedEp','concatTR','status');
    fprintf('%s\n', repmat('-',1,64));

    subjIDs = []; Z = []; nEpUsed = []; seen = [];

    for i = 1:numel(D)
        tok = regexp(D(i).name, 'p(\d+)_', 'tokens', 'once');
        if isempty(tok); continue; end
        N = str2double(tok{1});

        if ~isempty(subjects) && ~ismember(N, subjects); continue; end
        seen(end+1) = N; %#ok<AGROW>

        gmPath = fullfile(gmDir, sprintf('gbold_p%d_%s.mat', N, stageLabel));
        if exist(gmPath, 'file') ~= 2
            fprintf('P%-6d %8s %9s %10s   %s\n', N, '-','-','-','no gBOLD file -> skipped');
            continue
        end

        Cs = load(fullfile(D(i).folder, D(i).name));
        Gs = load(gmPath);

        % load the already-concatenated vectors (no maths here, just loading)
        c = double(loadStageSignal(Cs, D(i).name));   % CSF
        g = double(loadStageSignal(Gs, gmPath));      % gBOLD
        n = min(numel(c), numel(g));
        c = c(1:n); g = g(1:n);

        bounds = epochBounds(Cs.epochs, n);
        checkEpochsMatch(Cs.epochs, Gs.epochs, N);

        [zSubj, nUsed] = subjectZCurve(g, c, bounds, lagsTR, minOverlapTR, ...
                                       epochWeighting, TR, gboldTransform);

        if nUsed == 0
            fprintf('P%-6d %8d %9d %10d   %s\n', N, size(bounds,1), 0, n, ...
                    'no usable epoch -> skipped');
            continue
        end

        subjIDs(end+1) = N;      %#ok<AGROW>
        Z(end+1,:)     = zSubj;  %#ok<AGROW>
        nEpUsed(end+1) = nUsed;  %#ok<AGROW>

        fprintf('P%-6d %8d %9d %10d   %s\n', N, size(bounds,1), nUsed, n, '');
    end

    if ~isempty(subjects)
        for N = setdiff(subjects(:).', seen)
            fprintf('P%-6d %8s %9s %10s   %s\n', N, '-','-','-','no CSF file -> skipped');
        end
    end

    % keep only participants with a complete curve, so n is the same at
    % every lag and the reported df is unambiguous
    if ~isempty(Z)
        bad = any(~isfinite(Z), 2);
        if any(bad)
            warning('%s: dropping %d participant(s) with an incomplete z-curve: %s', ...
                    stageLabel, sum(bad), strjoin("P" + string(subjIDs(bad)), ', '));
            Z(bad,:) = []; subjIDs(bad) = []; nEpUsed(bad) = [];
        end
    end

    fprintf('%s\n', repmat('-',1,64));
    fprintf('Stage 1 done: %d participant(s) contribute a z-curve.\n', numel(subjIDs));

    out = struct('stageLabel',stageLabel, 'csfDir',csfDir, 'gmDir',gmDir, ...
                 'subjIDs',subjIDs, 'Z',Z, 'nEpUsed',nEpUsed);
end

function name = prettyStageName(stageLabel)
    % Readable condition name for figure text.
    %   "W"         -> "Wake"
    %   "N1_N2_N3"  -> "Sleep (N1, N2, N3)"
    %   "N2"        -> "Sleep (N2)"
    % Also removes the underscores, which MATLAB would otherwise render as
    % TeX subscripts in the legend (N1_N2_N3 came out as "N1_N2 3").
    s = string(stageLabel);
    if strcmpi(s, "W")
        name = "Wake";
    else
        parts = split(s, "_");
        name  = "Sleep (" + strjoin(parts.', ", ") + ")";
    end
end

function st = stage2(Z, alphaFDR)
    % Across-participant inference for ONE condition.
    nSubj = size(Z,1);
    st.meanZ = mean(Z, 1);
    st.sdZ   = std(Z, 0, 1);
    st.seZ   = st.sdZ / sqrt(nSubj);
    st.tStat = st.meanZ ./ st.seZ;
    st.pRaw  = tTestP(st.tStat, nSubj - 1);
    [st.sigFDR, st.pAdj] = fdrBH(st.pRaw, alphaFDR);
    st.meanR = tanh(st.meanZ);
    st.ciLoR = tanh(st.meanZ - st.seZ);
    st.ciHiR = tanh(st.meanZ + st.seZ);
end


%% ======================= STAGE 1 HELPERS =======================
function [zSubj, nUsed] = subjectZCurve(g, c, bounds, lagsTR, minOverlapTR, ...
                                        weighting, TR, gboldTransform)
    % One participant -> one Fisher-z value per lag.
    % Every correlation is computed INSIDE one epoch, on the overlapping
    % window only, so a lag never mixes samples across an epoch border.
    nL   = numel(lagsTR);
    acc  = zeros(1, nL);        % sum of  w * z
    wsum = zeros(1, nL);        % sum of  w
    used = false(size(bounds,1), 1);

    for e = 1:size(bounds,1)
        a = bounds(e,1); b = bounds(e,2);
        ge = g(a:b); ce = c(a:b);

        % optional transform of gBOLD, applied INSIDE the epoch so that a
        % derivative never spans a concatenation join
        [ge, ce] = applyGboldTransform(ge, ce, gboldTransform, TR);
        if numel(ge) < minOverlapTR; continue; end

        for k = 1:nL
            L = lagsTR(k);
            [x, y] = shiftPair(ge, ce, L);      % <-- the lag mechanics
            nOv = numel(x);
            if nOv < minOverlapTR; continue; end

            r = pear(x, y);
            if ~isfinite(r); continue; end
            r = min(max(r, -0.999999), 0.999999);   % keep atanh finite
            z = atanh(r);

            switch string(weighting)
                case "invvar", w = max(nOv - 3, 1);  % 1/var of a Fisher-z
                otherwise,     w = 1;                % "equal"
            end
            acc(k)  = acc(k)  + w*z;
            wsum(k) = wsum(k) + w;
            used(e) = true;
        end
    end

    zSubj = acc ./ wsum;            % weighted mean Fisher-z per lag
    zSubj(wsum == 0) = NaN;
    nUsed = sum(used);
end

function [ge, ce] = applyGboldTransform(ge, ce, mode, TR)
    % Turns the gBOLD STATE into a FLOW, so that it is the same kind of
    % quantity as the CSF inflow signal. Both series are returned, because
    % they must always be trimmed identically (see below).
    switch string(mode)
        case "none"
            return                      % leave both series untouched

        case {"negderiv", "negderiv_thresh"}
            % CENTRED difference: gradient(x,TR) uses the sample BEFORE and
            % the sample AFTER, so the result is timed exactly on the current
            % volume. A backward difference (diff) describes the change
            % between two volumes and therefore belongs half a volume earlier;
            % using it would bias every lag by TR/2 = 1.25 s.
            ge = -gradient(ge, TR);     % positive = blood volume FALLING

            if string(mode) == "negderiv_thresh"
                % keep only the phase in which blood is leaving; must come
                % AFTER the sign flip, or the wrong half survives
                ge = max(ge, 0);
            end

            % gradient falls back to a ONE-SIDED difference at the first and
            % last sample, which carries exactly the timing bias avoided
            % above. Drop those two samples - and drop the SAME samples from
            % the CSF signal, otherwise the two series shift against each
            % other by one volume without any error being raised.
            ge = ge(2:end-1);
            ce = ce(2:end-1);

        otherwise
            error('Unknown gboldTransform "%s".', mode);
    end
end

function [x, y] = shiftPair(g, c, L)
    % THE LAG MECHANICS.  Convention: r(L) = corr( g(t), c(t+L) ).
    % No padding and no wrapping: we simply take the window where both
    % signals exist after sliding CSF by L samples. Both outputs have
    % length ne-|L| and are aligned element by element.
    ne = numel(g);
    if L >= 0
        % CSF sampled LATER: pair g(1..ne-L) with c(1+L..ne)
        x = g(1:ne-L);        y = c(1+L:ne);
    else
        % CSF sampled EARLIER: pair g(1+|L|..ne) with c(1..ne-|L|)
        m = -L;
        x = g(1+m:ne);        y = c(1:ne-m);
    end
end

function bounds = epochBounds(epochs, nMax)
    % Start/end index of each epoch inside the concatenated signal,
    % clipped to the length actually available in both files.
    bounds = zeros(numel(epochs), 2);
    for e = 1:numel(epochs)
        bounds(e,:) = [epochs(e).concat_start, min(epochs(e).concat_end, nMax)];
    end
    bounds = bounds(bounds(:,2) >= bounds(:,1), :);
end

function checkEpochsMatch(epC, epG, N)
    % CSF and gBOLD epochs must describe the same stretches of the night.
    if numel(epC) ~= numel(epG)
        warning('P%d: CSF has %d epochs but gBOLD has %d - pairing by index.', ...
                N, numel(epC), numel(epG));
        return
    end
    sC = [epC.src_start_TR]; eC = [epC.src_end_TR];
    sG = [epG.src_start_TR]; eG = [epG.src_end_TR];
    if ~isequal(sC, sG) || ~isequal(eC, eG)
        warning('P%d: CSF and gBOLD epoch boundaries differ - check the segmentation.', N);
    end
end

function v = loadStageSignal(S, src)
    % PURE LOADER - does no maths and concatenates nothing.
    % The concatenation already happened in segment_stable_sleep_epochs.m,
    % which stored the finished vector under one of two names:
    %   stage_signal  (current script)
    %   n2_signal     (older _N2 script, still used by the N2 folder)
    % This just picks whichever name is present.
    % The epoch borders inside that vector are recovered separately by
    % epochBounds(), and subjectZCurve() correlates strictly within them.
    if     isfield(S, 'stage_signal'); v = S.stage_signal(:);
    elseif isfield(S, 'n2_signal');    v = S.n2_signal(:);
    else
        error('Neither "stage_signal" nor "n2_signal" found in %s', char(src));
    end
end

function r = pear(x, y)
    % Pearson correlation, base MATLAB (no toolbox).
    x = x(:); y = y(:); nn = numel(x);
    dx = x - sum(x)/nn;  dy = y - sum(y)/nn;
    d  = sqrt(sum(dx.^2) * sum(dy.^2));
    if d == 0, r = NaN; else, r = sum(dx.*dy) / d; end
end


